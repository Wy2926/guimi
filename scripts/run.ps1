param(
    [string]$Godot,
    [switch]$Editor,
    [switch]$Verify,
    [switch]$HuntianDemo,
    [switch]$CombatDemo,
    [ValidateSet(60, 120)][int]$VerifyFps = 120,
    [ValidateRange(1, 80)][int]$PerfEnemies = 80,
    [switch]$Headless
)
$ErrorActionPreference = 'Stop'
if ($HuntianDemo -and ($Verify -or $Editor)) { throw '-HuntianDemo cannot be combined with -Verify or -Editor.' }
if ($CombatDemo -and ($Verify -or $Editor -or $HuntianDemo)) { throw '-CombatDemo cannot be combined with -Verify, -Editor or -HuntianDemo.' }
$projectPath = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$candidates = @(
    $Godot,
    $env:GODOT_PATH,
    (Get-Command godot -ErrorAction SilentlyContinue).Source,
    'D:\Program Files (x86)\Godot_v4.7.2-stable_win64.exe\Godot_v4.7.2-stable_win64.exe'
) | Where-Object { $_ -and (Test-Path -LiteralPath $_ -PathType Leaf) }
if (!$candidates) {
    throw 'Godot 4.6+ was not found. Pass -Godot C:\path\Godot.exe, set GODOT_PATH, or import project.godot in Godot.'
}
$engine = @($candidates)[0]
# Official Windows archives ship a console wrapper; it preserves output and exit status.
$consoleEngine = $engine -replace '\.exe$', '_console.exe'
if (!$engine.EndsWith('_console.exe') -and (Test-Path -LiteralPath $consoleEngine)) {
    $engine = $consoleEngine
}
# Imported resources are generated by Godot, never hand-maintained.
if (!(Test-Path -LiteralPath (Join-Path $projectPath '.godot\imported'))) {
    & $engine --headless --editor --path $projectPath --import | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'Godot asset import failed.' }
}
$arguments = @('--path', $projectPath)
# Automated verification must never open a game window or steal desktop focus.
if ($Headless -or $Verify) { $arguments += '--headless' }
if ($Editor) { $arguments += '--editor' }
if ($Verify) {
    $arguments += @('--', '--verify', "--fps=$VerifyFps", "--perf-enemies=$PerfEnemies")
}
if ($HuntianDemo) { $arguments += @('--', '--huntian-demo') }
if ($CombatDemo) { $arguments += @('--', '--combat-demo', "--fps=$VerifyFps") }
& $engine @arguments | Out-Host
if ($null -ne $LASTEXITCODE -and $LASTEXITCODE -ne 0) {
    throw "Godot exited with code $LASTEXITCODE."
}
